/**
 * Writes dist/sw.js: precaches every file of the production build (fully offline after first load / install),
 * cache-first for same-origin GETs, versioned by a hash of the file list so updates replace the old cache.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const DIST = path.resolve('dist');
const files: string[] = [];
const walk = (d: string) => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name !== 'sw.js') files.push(path.relative(DIST, p).split(path.sep).join('/'));
  }
};
walk(DIST);
const hash = crypto.createHash('sha1');
for (const f of files.sort()) hash.update(f + ':' + fs.statSync(path.join(DIST, f)).size);
const version = hash.digest('hex').slice(0, 12);
const total = files.reduce((a, f) => a + fs.statSync(path.join(DIST, f)).size, 0);
const sw = `/* Settimo Mondo service worker — generated by tools/gen-sw.ts */
const CACHE = 'settimo-mondo-${version}';
const PRECACHE = ${JSON.stringify(['./', ...files.map((f) => './' + f)])};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('settimo-mondo-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
      return res;
    }).catch(() => caches.match('./')))
  );
});
`;
fs.writeFileSync(path.join(DIST, 'sw.js'), sw);
console.log(`gen-sw: ${files.length} files precached (${(total / 1048576).toFixed(1)} MB), cache ${version}`);
