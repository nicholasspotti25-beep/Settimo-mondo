/**
 * Generates content registries from the folders in src/content:
 *   src/generated/registry.sim.ts    — behaviors (sim-safe; static imports)
 *   src/generated/registry.render.ts — boss models, arena builders, zone/landmark builders, form environments (lazy imports per act)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT = path.join(ROOT, 'src/content');
const OUT = path.join(ROOT, 'src/generated');
fs.mkdirSync(OUT, { recursive: true });

function dirs(p: string): string[] {
  if (!fs.existsSync(p)) return [];
  return fs.readdirSync(p, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
}
function has(p: string): boolean {
  return fs.existsSync(p);
}

// Behaviors: src/content/bosses/<id>/behavior.ts (default export: BehaviorFactory). Minion behaviors: minion_<minion>.ts -> "<boss>:<minion>"
const simLines: string[] = ['// Generated by tools/gen-registry.ts — do not edit.', "import type { BehaviorRegistry } from '../sim/behavior';"];
const entries: string[] = [];
let n = 0;
for (const id of dirs(path.join(CONTENT, 'bosses'))) {
  const dir = path.join(CONTENT, 'bosses', id);
  if (has(path.join(dir, 'behavior.ts'))) {
    const v = `b${n++}`;
    simLines.push(`import ${v} from '../content/bosses/${id}/behavior';`);
    entries.push(`  ${JSON.stringify(id)}: ${v},`);
  }
  for (const f of fs.readdirSync(dir).filter((x) => /^minion_.*\.ts$/.test(x)).sort()) {
    const v = `b${n++}`;
    const mid = f.replace(/^minion_/, '').replace(/\.ts$/, '');
    simLines.push(`import ${v} from '../content/bosses/${id}/${f.replace(/\.ts$/, '')}';`);
    entries.push(`  ${JSON.stringify(`${id}:${mid}`)}: ${v},`);
  }
}
simLines.push('', 'export const BEHAVIORS: BehaviorRegistry = {', ...entries, '};', '');
fs.writeFileSync(path.join(OUT, 'registry.sim.ts'), simLines.join('\n'));

// Render registry: lazy loaders keyed by id.
const r: string[] = ['// Generated by tools/gen-registry.ts — do not edit.', '/* eslint-disable */', 'type Loader = () => Promise<any>;', ''];
const models: string[] = [];
const arenas: string[] = [];
for (const id of dirs(path.join(CONTENT, 'bosses'))) {
  const dir = path.join(CONTENT, 'bosses', id);
  if (has(path.join(dir, 'model.ts'))) models.push(`  ${JSON.stringify(id)}: () => import('../content/bosses/${id}/model'),`);
  if (has(path.join(dir, 'arena.ts'))) {
    // keyed by arena id (read from data/bosses/<id>.yaml) so bosses sharing an arena share its builder
    const yml = path.join(ROOT, 'data/bosses', `${id}.yaml`);
    const arenaId = has(yml) ? (YAML.parse(fs.readFileSync(yml, 'utf8'))?.arena as string | undefined) : undefined;
    const key = arenaId ?? id;
    if (!arenas.some((l) => l.startsWith(`  ${JSON.stringify(key)}:`))) arenas.push(`  ${JSON.stringify(key)}: () => import('../content/bosses/${id}/arena'),`);
  }
}
const zones: string[] = [];
for (const id of dirs(path.join(CONTENT, 'zones'))) {
  if (has(path.join(CONTENT, 'zones', id, 'zone.ts'))) zones.push(`  ${JSON.stringify(id)}: () => import('../content/zones/${id}/zone'),`);
}
const forms: string[] = [];
for (const id of dirs(path.join(CONTENT, 'forms'))) {
  if (has(path.join(CONTENT, 'forms', id, 'environment.ts'))) forms.push(`  ${JSON.stringify(id)}: () => import('../content/forms/${id}/environment'),`);
}
r.push('/** Boss model modules (default export: BossModelBuilder). */', 'export const BOSS_MODELS: Record<string, Loader> = {', ...models, '};', '');
r.push('/** Arena dressing modules keyed by ARENA id (default export: ArenaBuilder). */', 'export const ARENA_BUILDERS: Record<string, Loader> = {', ...arenas, '};', '');
r.push('/** Zone builders (default export: ZoneBuilder). */', 'export const ZONE_BUILDERS: Record<string, Loader> = {', ...zones, '};', '');
r.push('/** Metamondo Form environments (default export: FormEnvironmentBuilder). */', 'export const FORM_ENVIRONMENTS: Record<string, Loader> = {', ...forms, '};', '');
fs.writeFileSync(path.join(OUT, 'registry.render.ts'), r.join('\n'));
// Bot hooks: tools/bot/hooks/<boss>.ts (default export: BotHook)
const HOOK_DIR = path.join(ROOT, 'tools/bot/hooks');
fs.mkdirSync(HOOK_DIR, { recursive: true });
const hookFiles = fs.readdirSync(HOOK_DIR).filter((f) => f.endsWith('.ts') && f !== 'index.ts').sort();
const hl: string[] = ['// Generated by tools/gen-registry.ts — do not edit.', "import type { BotHook } from '../hooks';"];
hookFiles.forEach((f, i) => hl.push(`import h${i} from './${f.replace(/\.ts$/, '')}';`));
hl.push('', 'export const BOT_HOOKS: Record<string, BotHook> = {', ...hookFiles.map((f, i) => `  ${JSON.stringify(f.replace(/\.ts$/, ''))}: h${i},`), '};', '');
fs.writeFileSync(path.join(HOOK_DIR, 'index.ts'), hl.join('\n'));
console.log(`gen-registry: ${entries.length} behaviors, ${models.length} models, ${arenas.length} arenas, ${zones.length} zones, ${forms.length} forms`);
